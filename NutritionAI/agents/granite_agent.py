def get_iam_token(api_key: str) -> str:
    """Obtain IBM Cloud IAM access token."""
    url = "https://iam.cloud.ibm.com/identity/token"
    headers = {"Content-Type": "application/x-www-form-urlencoded"}
    data = f"grant_type=urn:ibm:params:oauth:grant-type:apikey&apikey={api_key}"
    resp = requests.post(url, headers=headers, data=data, timeout=30)
    resp.raise_for_status()
    return resp.json()["access_token"]


def apply_guardrails(text: str) -> dict:
    """
    Agentic Guardrail Layer:
    - Screens input/output for harmful content
    - Enforces ethical AI boundaries
    - Returns {safe: bool, reason: str}
    """
    text_lower = text.lower()
    for keyword in HARMFUL_KEYWORDS:
        if keyword in text_lower:
            return {
                "safe": False,
                "reason": f"Content flagged for potentially harmful advice: '{keyword}'. "
                          "Please consult a healthcare professional for personalised guidance."
            }
    return {"safe": True, "reason": ""}


