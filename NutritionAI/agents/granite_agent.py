def call_granite_api(prompt: str) -> str:
    """
    Agentic Execution Layer:
    Calls IBM Granite via watsonx.ai REST API with robust error handling.
    """
    try:
        # Re-read env vars at call time to pick up user-provided keys
        api_key = os.environ.get("WATSONX_API_KEY", WATSONX_API_KEY)
        project_id = os.environ.get("WATSONX_PROJECT_ID", WATSONX_PROJECT_ID)
        api_url = os.environ.get("WATSONX_API_URL", WATSONX_API_URL)

        # Skip API call if placeholder key is still set
        if not api_key or api_key == "YOUR_IBM_WATSONX_API_KEY":
            return None

        # Get IAM token
        token = get_iam_token(api_key)

        url = f"{api_url}/ml/v1-beta/generation/text"
        headers = {
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "Accept": "application/json"
        }
        payload = {
            "model_id": GRANITE_MODEL_ID,
            "input": prompt,
            "parameters": {
                "decoding_method": "greedy",
                "max_new_tokens": 2000,
                "min_new_tokens": 100,
                "stop_sequences": [],
                "repetition_penalty": 1.1,
                "temperature": 0.7
            },
            "project_id": project_id
        }
        response = requests.post(url, headers=headers, json=payload, timeout=60)
        response.raise_for_status()
        result = response.json()
        generated_text = result.get("results", [{}])[0].get("generated_text", "")
        return generated_text.strip()

    except requests.exceptions.ConnectionError:
        return None
    except requests.exceptions.Timeout:
        return None
    except Exception:
        return None


