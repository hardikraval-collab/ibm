def generate_nutrition_plan(user_data: dict) -> dict:
    """
    Main Agentic Orchestrator:
    1. Validate input (Guardrails)
    2. Build prompt (Planning)
    3. Call IBM Granite (Execution)
    4. Post-process output (Reflection)
    5. Return structured response
    """
    # Step 1: Input Guardrails
    input_text = json.dumps(user_data)
    guard = apply_guardrails(input_text)
    if not guard["safe"]:
        return {
            "success": False,
            "error": guard["reason"],
            "plan": None
        }

    # Step 2: Build structured prompt
    prompt = build_nutrition_prompt(user_data)

    # Step 3: Call IBM Granite LLM
    granite_response = call_granite_api(prompt)

    # Step 4: Use fallback if API unavailable
    if not granite_response:
        plan_text = generate_fallback_plan(user_data)
        source = "rule-based-ai"
    else:
        # Step 5: Output Guardrails
        output_guard = apply_guardrails(granite_response)
        if not output_guard["safe"]:
            plan_text = generate_fallback_plan(user_data)
            source = "rule-based-ai"
        else:
            plan_text = granite_response
            source = "ibm-granite"

    # Add medical disclaimer
    disclaimer = MEDICAL_DISCLAIMER.format(date=datetime.now().strftime("%B %d, %Y"))
    full_plan = plan_text + "\n\n" + disclaimer

    return {
        "success": True,
        "plan": full_plan,
        "source": source,
        "generated_at": datetime.now().isoformat()
    }


def answer_nutrition_query(question: str, user_context: dict = None) -> dict:
    """
    Agentic Q&A Resolver:
    Answers user nutrition questions using IBM Granite.
    """
    # Input Guardrails
    guard = apply_guardrails(question)
    if not guard["safe"]:
        return {
            "success": False,
            "answer": guard["reason"]
        }

    prompt = build_query_prompt(question, user_context)
    answer = call_granite_api(prompt)

    if not answer:
        # Fallback Q&A responses
        answer = generate_fallback_answer(question)

    return {
        "success": True,
        "answer": answer,
        "disclaimer": "This information is for educational purposes only. Consult a healthcare professional for medical advice."
    }


